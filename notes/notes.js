  function hydSVG(task) {
    const svg = S('svg', { class: 'dia' });
    const T = TASKS[task];
    const D = new HYD.HydDiagram(svg, T.hydSize[0], T.hydSize[1]);
    T.build(D)(new Sim(T));
    D.applyLines({});
    return svg;
  }

