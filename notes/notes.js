  function hydSVG(task) {
    const svg = S('svg', { class: 'dia' });
    const T = TASKS[task];
    const D = new HYD.HydDiagram(svg, T.hydSize[0], T.hydSize[1]);
    T.build(D)(new Sim(T));
    D.applyLines({});
    return svg;
  }
  function ladderSVG(task) {
    const svg = S('svg', { class: 'dia lad' });
    const lad = new Ladder(svg, TASKS[task].ladder, {});
    // 원래 회로도처럼: 릴레이 모두 OFF, LS1만 눌린(⇧) 상태
    lad.update({ closed: el => (el.ref === 'LS1' ? true : el.kind === 'nc'), coilOn: () => false, coilPending: () => false });
    return svg;
  }
  const list = items => `<ul>${items.map(x => `<li>${b(x)}</li>`).join('')}</ul>`;
  const table = rows => `<table class="tb"><tr><th>단계</th><th>동작 내용</th><th>센서 검출</th><th>여자 릴레이</th><th>동작 솔레노이드</th><th>속도 및 상태 특징</th></tr>${rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</table>`;

  function taskPage(id) {
    const P = PAGES[id];
    const sec = document.createElement('section');
    sec.className = 'page';
    sec.innerHTML = `
      <header><h1>${P.title}</h1>${P.motto ? `<span class="sub">${b(P.motto)}</span>` : ''}<span class="src">${P.src}</span></header>
      <div class="top"><div class="fig" id="fig-${id}"></div><div class="fig" id="lad-${id}"></div></div>
      <div class="box"><div class="bt">부품 명칭</div><ul class="parts">${P.parts.map(x => `<li>${b(x)}</li>`).join('')}</ul></div>
      ${P.table ? `<div class="box"><div class="bt">스텝별 동작 요약</div>${table(P.table)}</div>` : ''}
      ${P.blocks.map(([t, items]) => `<div class="box"><div class="bt">${t}</div>${list(items)}</div>`).join('')}
      ${id === 't1' ? '<p class="mark">※ 표시는 노트 원문과 회로도가 달라 회로도 기준으로 고친 문장 (4쪽 아래 참고)</p>' : ''}`;
    sec.querySelector('#fig-' + id).append(hydSVG(id));
    sec.querySelector('#lad-' + id).append(ladderSVG(id));
    return sec;
  }

